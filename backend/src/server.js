'use strict';
require('dotenv').config({path:require('path').resolve(__dirname,'../../.env')});
const express=require('express');
const cors=require('cors');
const helmet=require('helmet');
const {generalLimiter}=require('./middleware/rateLimiter');
const {authenticate,secret}=require('./middleware/auth');
if(!process.env.DATABASE_URL)throw new Error('DATABASE_URL is required');
secret();
const origins=String(process.env.ALLOWED_ORIGINS||'').split(',').map(value=>value.trim()).filter(Boolean);
if(!origins.length)throw new Error('ALLOWED_ORIGINS is required');
const app=express();
app.use(helmet());
app.use(cors({credentials:true,origin:(origin,callback)=>(!origin||origins.includes(origin))?callback(null,true):callback(new Error('origin not allowed'))}));
app.use(express.json({limit:'10mb'}));
app.use('/api/',generalLimiter);
app.get('/api/health',(_req,res)=>res.json({status:'ok',service:'governed-social-media'}));
app.use('/api/auth',require('./routes/auth'));
app.use('/api/ai',require('./routes/ai'));
app.use('/api/governed-content',require('./routes/governedContent')(authenticate));
app.use('/api',(_req,res)=>res.status(404).json({error:'Not found'}));
const port=Number(process.env.BACKEND_PORT||3001);
app.listen(port,()=>console.log(`Governed social-media API listening on ${port}`));
module.exports=app;
